def seed_posters(stdout, style):
    created = 0
    for data in POSTERS:
        _, is_new = Poster.objects.get_or_create(title=data["title"], date=data["date"], defaults=data)
        created += is_new
    if created:
        stdout.write(style.SUCCESS(f"Афиша: добавлено событий — {created}."))


# Учебная учётка администратора. Только для локального запуска!
ADMIN_USERNAME = "admin"
ADMIN_PASSWORD = "podzemka2026"


def seed_admin(stdout, style):
    User = get_user_model()
    if not User.objects.filter(username=ADMIN_USERNAME).exists():
        User.objects.create_superuser(ADMIN_USERNAME, "", ADMIN_PASSWORD)
        stdout.write(style.SUCCESS(f"Администратор создан: {ADMIN_USERNAME} / {ADMIN_PASSWORD}"))


class Command(BaseCommand):
    help = "Наполняет базу демо-данными: залы, меню, форматы, отзывы, FAQ."

    def add_arguments(self, parser):
        parser.add_argument("--flush", action="store_true", help="Удалить существующий контент перед заполнением")

    @transaction.atomic
    def handle(self, *args, **options):
        if options["flush"]:
            for model in (Hall, EventFormat, MenuPackage, Review, FAQ, Poster):
                model.objects.all().delete()

        seed_admin(self.stdout, self.style)
        seed_posters(self.stdout, self.style)

        if Hall.objects.exists():
            self.stdout.write(self.style.WARNING("Данные уже есть. Используйте --flush, чтобы пересоздать."))
            return

        for data in HALLS:
            Hall.objects.create(**data)
        for i, (title, icon, desc) in enumerate(FORMATS):
            EventFormat.objects.create(title=title, icon=icon, description=desc, order=i)
        for i, (name, desc, price, featured, items) in enumerate(PACKAGES):
            MenuPackage.objects.create(
                name=name, description=desc, price_per_person=price,
                is_featured=featured, items=items, order=i,
            )
        today = datetime.date.today()
        for author, event, text, rating, days_ago in REVIEWS:
            Review.objects.create(
                author=author, event=event, text=text, rating=rating,
                created_at=today - datetime.timedelta(days=days_ago),
            )
        for i, (q, a) in enumerate(FAQS):
            FAQ.objects.create(question=q, answer=a, order=i)

        self.stdout.write(self.style.SUCCESS("Готово! Подземка наполнена демо-данными."))
